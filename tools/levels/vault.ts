  grp('house.count');
  G.bulb(16.0, 12.9, 'bulb_count', 'count', true);
  T.lights.find(l => l.name === 'bulb_count')!.mains = true;
  G.table(14.9, 16.2, 1.6, 0.7); G.plasticChair(14.9, 15.45, Math.PI);          // the clerk's desk, against the south wall
  G.table(17.3, 9.62, 1.5, 0.6); G.trunk(13.75, 10.1, HALF, 'paintBlue');         // the counting table under the lens · the day's takings
  G.rug(15.9, 13.0, 2.6, 1.7, 'afghan'); G.toshak(17.9, 15.6, 1.9, HALF); G.lowTable(16.7, 15.6, 0);   // where clients sit and wait
  G.crates(13.8, 11.6, 0.05, 2, 'ply');

  grp('house.strong');
  G.bulb(21.5, 13.2, 'bulb_strong', 'strong', false);
  // the safe, against the north wall: an iron box on a plinth, a door plate and a wheel on its face
  T.add({ c: [21.5, 0.06, 9.52], h: [0.5, 0.06, 0.38], ...GWOT_MATERIALS.block });
